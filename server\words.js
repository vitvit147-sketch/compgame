export function getRandomWord(excludeList = []) {
  const available = WORDS_DATABASE.filter(item => !excludeList.includes(item.word));
  if (available.length === 0) {
    return WORDS_DATABASE[Math.floor(Math.random() * WORDS_DATABASE.length)];
  }
  return available[Math.floor(Math.random() * available.length)];
}
