export const ALL_DANETKI = EXPANDED_DATABASE;

export function getRandomDanetka(category = 'all', completedIds = []) {
  let pool = ALL_DANETKI;
  if (category && category !== 'all') {
    pool = pool.filter(d => d.category === category);
  }
  // Отфильтровываем уже пройденные
  const available = pool.filter(d => !completedIds.includes(d.id));
  const targetPool = available.length > 0 ? available : pool;
  return targetPool[Math.floor(Math.random() * targetPool.length)];
}

export function getDanetkiByCategory(category = 'all') {
  if (!category || category === 'all') return ALL_DANETKI;
  return ALL_DANETKI.filter(d => d.category === category);
}
