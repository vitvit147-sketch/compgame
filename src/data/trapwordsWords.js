export function getRandomWord(usedWords = []) {
  const available = WORDS_DATABASE.filter(w => !usedWords.includes(w.word));
  const pool = available.length > 0 ? available : WORDS_DATABASE;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
