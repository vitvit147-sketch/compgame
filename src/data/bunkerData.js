export function generateCharacter() {
  const pick = arr => arr[Math.floor(Math.random() * arr.length)];
  return {
    profession: { ...pick(PROFESSIONS), revealed: false },
    biology: { ...pick(BIOLOGIES), revealed: false },
    health: { ...pick(HEALTHS), revealed: false },
    hobby: { ...pick(HOBBIES), revealed: false },
    baggage: { ...pick(BAGGAGES), revealed: false },
    fact: { ...pick(FACTS), revealed: false },
    specialCondition: { ...pick(SPECIAL_CONDITIONS), used: false, revealed: false }
  };
}

export function getRandomCatastrophe() {
  return CATASTROPHES[Math.floor(Math.random() * CATASTROPHES.length)];
}

export function getRandomBunkerRooms(count = 5) {
  const shuffled = [...BUNKER_ROOMS].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

export function getRandomThreats(count = 2) {
  const shuffled = [...FINALE_THREATS].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
