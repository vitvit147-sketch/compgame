// Функция перемешивания Фишера-Йетса
function shuffle(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// Генерация уникальных наборов карт для всех игроков в комнате (без повторов!)
export function generateUniqueCharacters(count) {
  const shuffledProfessions = shuffle(PROFESSIONS);
  const shuffledBiologies = shuffle(BIOLOGIES);
  const shuffledHealths = shuffle(HEALTHS);
  const shuffledHobbies = shuffle(HOBBIES);
  const shuffledBaggages = shuffle(BAGGAGES);
  const shuffledFacts = shuffle(FACTS);
  const shuffledSpecials = shuffle(SPECIAL_CONDITIONS);

  const characters = [];
  for (let i = 0; i < count; i++) {
    characters.push({
      profession: { ...shuffledProfessions[i % shuffledProfessions.length], revealed: false },
      biology: { ...shuffledBiologies[i % shuffledBiologies.length], revealed: false },
      health: { ...shuffledHealths[i % shuffledHealths.length], revealed: false },
      hobby: { ...shuffledHobbies[i % shuffledHobbies.length], revealed: false },
      baggage: { ...shuffledBaggages[i % shuffledBaggages.length], revealed: false },
      fact: { ...shuffledFacts[i % shuffledFacts.length], revealed: false },
      specialCondition: { ...shuffledSpecials[i % shuffledSpecials.length], used: false, revealed: false }
    });
  }
  return characters;
}

