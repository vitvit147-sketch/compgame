export function getRandomLocation(selectedCategories = ['classic', 'travel', 'adventure', 'work', 'crazy']) {
  const filtered = SPY_LOCATIONS.filter(loc => selectedCategories.includes(loc.category));
  const pool = filtered.length > 0 ? filtered : SPY_LOCATIONS;
  return pool[Math.floor(Math.random() * pool.length)];
}
